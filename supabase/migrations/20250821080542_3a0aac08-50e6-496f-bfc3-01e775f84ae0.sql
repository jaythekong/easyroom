-- Fix the final two trigger functions that need search_path hardening

CREATE OR REPLACE FUNCTION public.update_ticker_messages_updated_at()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$function$;

